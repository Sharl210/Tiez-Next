/**
 * 标签候补列表最多显示几**行**（超出由列表自身滚动查看）。
 *
 * 【为什么是行数而不是像素】用户要的是"最多展示 4 行，超过可以用鼠标滚动查看"。
 * 写死像素高度会在用户调整字号后失效（要么显示不满 4 行，要么露出第 5 行半截）。
 * 行数在这里控制**条数**，CSS 侧用 `calc(rows × <单行高>)` 控制**可见高度**，
 * 两者都以"行"为单位，字号变了仍成立。
 *
 * 该值通过内联 `--tag-suggest-rows` 传给 `tags.css`，**CSS 里不要再写一遍 4**。
 */
export const TAG_SUGGEST_VISIBLE_ROWS = 4;

/** 取这么多条就够填满可见区并留出滚动余量；再多只是白占内存。 */
export const TAG_SUGGEST_LIST_MAX = 40;
